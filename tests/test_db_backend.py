from __future__ import annotations

from huishi.db_backend import (
    DatabaseSettings,
    PostgreSQLConnection,
    add_returning_id_if_needed,
    database_settings_from_mapping,
    postgres_schema_from_sqlite,
    rewrite_insert_or_ignore,
    split_sql_script,
    translate_qmark_placeholders,
)


def test_database_settings_default_to_sqlite_database_path(tmp_path):
    settings = database_settings_from_mapping({"DATABASE": tmp_path / "huishi.sqlite3"})

    assert settings == DatabaseSettings(backend="sqlite", dsn=str(tmp_path / "huishi.sqlite3"))


def test_database_settings_use_postgres_database_url():
    settings = database_settings_from_mapping(
        {
            "DATABASE": "ignored.sqlite3",
            "DATABASE_URL": "postgresql://huishi:secret@127.0.0.1:5432/huishi",
        }
    )

    assert settings.backend == "postgresql"
    assert settings.dsn == "postgresql://huishi:secret@127.0.0.1:5432/huishi"


def test_translate_qmark_placeholders_skips_quoted_question_marks():
    sql = "SELECT * FROM records WHERE prompt = '?' AND id = ? AND note = \"?\" AND user_id = ?"

    assert translate_qmark_placeholders(sql) == (
        "SELECT * FROM records WHERE prompt = '?' AND id = %s AND note = \"?\" AND user_id = %s"
    )


def test_translate_qmark_placeholders_handles_escaped_single_quotes():
    sql = "SELECT 'it''s ?' AS text, id FROM records WHERE id = ?"

    assert translate_qmark_placeholders(sql) == "SELECT 'it''s ?' AS text, id FROM records WHERE id = %s"


def test_split_sql_script_ignores_semicolon_inside_quotes():
    script = "CREATE TABLE a (value TEXT DEFAULT ';'); CREATE TABLE b (id INTEGER);"

    assert split_sql_script(script) == [
        "CREATE TABLE a (value TEXT DEFAULT ';')",
        "CREATE TABLE b (id INTEGER)",
    ]


def test_rewrite_insert_or_ignore_for_postgresql_conflict_handling():
    sql = "INSERT OR IGNORE INTO users (username, password_hash) VALUES (?, ?)"

    assert rewrite_insert_or_ignore(sql) == (
        "INSERT INTO users (username, password_hash) VALUES (?, ?) ON CONFLICT DO NOTHING"
    )


def test_add_returning_id_only_for_tables_with_integer_identity():
    sql = "INSERT INTO records (user_id, prompt) VALUES (?, ?)"
    user_settings_sql = "INSERT INTO user_settings (user_id, api_key, updated_at) VALUES (?, ?, ?)"

    assert add_returning_id_if_needed(sql) == "INSERT INTO records (user_id, prompt) VALUES (?, ?) RETURNING id"
    assert add_returning_id_if_needed(user_settings_sql) == user_settings_sql
    assert add_returning_id_if_needed(sql + " RETURNING id") == sql + " RETURNING id"


class FakeCursor:
    rowcount = 1

    def __init__(self, row=None):
        self.row = row

    def fetchone(self):
        return self.row

    def fetchall(self):
        return [self.row] if self.row is not None else []


class FakeRawConnection:
    def __init__(self):
        self.executed = []
        self.commits = 0
        self.rollbacks = 0
        self.closed = False

    def execute(self, sql, params=()):
        self.executed.append((sql, tuple(params or ())))
        return FakeCursor({"id": 42} if "RETURNING id" in sql else None)

    def commit(self):
        self.commits += 1

    def rollback(self):
        self.rollbacks += 1

    def close(self):
        self.closed = True


def test_postgres_connection_translates_placeholders_and_exposes_lastrowid():
    raw = FakeRawConnection()
    db = PostgreSQLConnection(raw)

    cursor = db.execute("INSERT INTO records (user_id, prompt) VALUES (?, ?)", (7, "hello"))

    assert raw.executed == [("INSERT INTO records (user_id, prompt) VALUES (%s, %s) RETURNING id", (7, "hello"))]
    assert cursor.lastrowid == 42


def test_postgres_connection_rewrites_insert_or_ignore_and_executes_script():
    raw = FakeRawConnection()
    db = PostgreSQLConnection(raw)

    db.executescript("INSERT OR IGNORE INTO users (username) VALUES ('admin'); SELECT '?' AS marker;")

    assert raw.executed == [
        ("INSERT INTO users (username) VALUES ('admin') ON CONFLICT DO NOTHING RETURNING id", ()),
        ("SELECT '?' AS marker", ()),
    ]


def test_postgres_schema_from_sqlite_replaces_autoincrement_identity():
    schema = "CREATE TABLE users (id INTEGER PRIMARY KEY AUTOINCREMENT, elapsed_seconds REAL NOT NULL DEFAULT 0);"

    assert postgres_schema_from_sqlite(schema) == (
        "CREATE TABLE users (id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, elapsed_seconds DOUBLE PRECISION NOT NULL DEFAULT 0);"
    )


def test_postgres_schema_from_sqlite_orders_foreign_key_dependencies():
    schema = """
    CREATE TABLE IF NOT EXISTS records (id INTEGER PRIMARY KEY AUTOINCREMENT, dialogue_id INTEGER, FOREIGN KEY(dialogue_id) REFERENCES dialogues(id));
    CREATE TABLE IF NOT EXISTS dialogues (id INTEGER PRIMARY KEY AUTOINCREMENT);
    """

    converted = postgres_schema_from_sqlite(schema)

    assert converted.index("CREATE TABLE IF NOT EXISTS dialogues") < converted.index("CREATE TABLE IF NOT EXISTS records")
